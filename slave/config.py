# =============================================================================
# config.py — Конфигурация системы Master-Slave
# =============================================================================

# -----------------------------------------------------------------------------
# Сетевые порты
# -----------------------------------------------------------------------------

# UDP: широковещательный опрос сети (discovery)
UDP_BROADCAST_PORT = 50000

# TCP: основной канал связи Master ↔ Slave (передача задач и результатов)
TCP_PORT = 50001

# TCP: heartbeat-канал (проверка живости Slave)
HEARTBEAT_PORT = 50002

# -----------------------------------------------------------------------------
# Discovery (обнаружение Slave-машин)
# -----------------------------------------------------------------------------

# Широковещательный адрес локальной сети
BROADCAST_ADDRESS = "255.255.255.255"

# Сообщение-запрос от Master при опросе сети
DISCOVERY_REQUEST  = "MASTER_DISCOVERY"

# Сообщение-ответ от Slave, готового к работе
DISCOVERY_RESPONSE = "SLAVE_READY"

# Сколько секунд Master ждёт ответов от Slaves при опросе
DISCOVERY_TIMEOUT_SEC = 5.0

# -----------------------------------------------------------------------------
# Heartbeat (мониторинг живости)
# -----------------------------------------------------------------------------

# Сообщение-запрос пинга
HEARTBEAT_PING = "PING"

# Сообщение-ответ на пинг
HEARTBEAT_PONG = "PONG"

# Интервал между пингами (секунды)
HEARTBEAT_INTERVAL_SEC = 5.0

# Максимальное время ожидания ответа на пинг.
# Если Slave не ответил за это время — считается мёртвым (DEAD)
HEARTBEAT_TIMEOUT_SEC = 10.0

# Порт UDP для heartbeat-пингов (отдельный от discovery)
HEARTBEAT_UDP_PORT = 50003

# -----------------------------------------------------------------------------
# Передача данных (TCP)
# -----------------------------------------------------------------------------

# Размер буфера чтения сокета (байты)
SOCKET_BUFFER_SIZE = 4096

# Таймаут TCP-соединения (секунды)
SOCKET_TIMEOUT_SEC = 30.0

# Максимальный размер передаваемого файла (байты): 10 МБ
MAX_FILE_SIZE_BYTES = 10 * 1024 * 1024

# -----------------------------------------------------------------------------
# Задачи и результаты
# -----------------------------------------------------------------------------

# Статусы задач
TASK_STATUS_PENDING  = "PENDING"   # ожидает отправки
TASK_STATUS_SENT     = "SENT"      # отправлена Slave
TASK_STATUS_DONE     = "DONE"      # результат получен
TASK_STATUS_LOST     = "LOST"      # Slave упал, задача потеряна

# Статусы Slave-машин
SLAVE_STATUS_ALIVE   = "ALIVE"     # работает, отвечает на пинги
SLAVE_STATUS_BUSY    = "BUSY"      # выполняет задачу
SLAVE_STATUS_DEAD    = "DEAD"      # не отвечает

# Шаблон имени файла результата: {task_id}_{slave_ip}.result
# Пример: "a3f1c2d4_192.168.1.55.result"
RESULT_FILENAME_TEMPLATE = "{task_id}_{slave_ip}.result"

# Директория на Slave, куда сохраняется полученный скрипт
SLAVE_WORK_DIR = "./slave_workspace"

# Директория на Master, куда сохраняются файлы результатов
MASTER_RESULTS_DIR = "./master_results"

# -----------------------------------------------------------------------------
# Логирование
# -----------------------------------------------------------------------------

# Уровень логирования: DEBUG / INFO / WARNING / ERROR
LOG_LEVEL = "INFO"

# Формат строки лога
LOG_FORMAT = "[%(asctime)s] [%(levelname)s] %(message)s"

# Формат времени в логах
LOG_DATE_FORMAT = "%Y-%m-%d %H:%M:%S"
